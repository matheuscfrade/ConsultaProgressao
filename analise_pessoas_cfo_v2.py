PCCTAE_PADRAO_MAX = 19  # Lei 15.141/2025 (antes era 16)


def limpar_classe(classe):
    """Remove a palavra CLASSE e devolve só o código (C, D, T, DIV...)."""
    if pd.isna(classe):
        return "?"
    s = str(classe).strip().upper()
    s = s.replace("CLASSE", " ").replace("-", " ")
    partes = [p for p in s.split() if p]
    return partes[-1] if partes else "?"


def extrair_numero(valor):
    digitos = "".join(ch for ch in str(valor) if ch.isdigit())
    return int(digitos) if digitos else 0


def extrair_padrao(valor, maximo=PCCTAE_PADRAO_MAX):
    """
    Extrai o padrão de vencimento.
    Se vier composto (ex.: 409, 202), tenta os últimos 2 dígitos.
    """
    n = extrair_numero(valor)
    if 1 <= n <= maximo:
        return n
    s = "".join(ch for ch in str(valor) if ch.isdigit())
    if len(s) >= 2:
        n2 = int(s[-2:])
        if 1 <= n2 <= maximo:
            return n2
    if len(s) >= 1:
        n1 = int(s[-1])
        if 1 <= n1 <= maximo:
            return n1
    return n if n else 0


def aniversario_seguro(base, ano):
    """Evita ValueError em 29/02 de ano não-bissexto."""
    try:
        return datetime.date(ano, base.month, base.day)
    except ValueError:
        return datetime.date(ano, 2, 28)


def tem_doutorado(titulacao):
    if pd.isna(titulacao):
        return False
    t = str(titulacao).strip().upper()
    chaves = ("DOUTORADO", "DOUTOR", "DR.", "DR ", "PHD", "PH.D", "PH. D")
    return any(k in t for k in chaves)


def calcular_proximo_posicionamento(classe, padrao, cargo):
    classe_str = str(classe).strip().upper() if pd.notna(classe) else ""
    classe_cod = limpar_classe(classe)
    is_ebtt = "PROFESSOR" in str(cargo).upper()
    padrao_num = extrair_padrao(padrao, maximo=4 if is_ebtt else PCCTAE_PADRAO_MAX)

    # Já no topo EBTT
    if classe_cod in {"T", "TITULAR"} or "TITULAR" in classe_str:
        return "TITULAR"

    if is_ebtt:
        if padrao_num >= 4:
            if "DIV" in classe_str or classe_cod in {"C", "DIV"}:
                return "TITULAR"
            # Alterado: 'B' agora progride para DIII-1
            if "DIII" in classe_str or classe_cod in {"DIII"}:
                return "DIV-1"
            if "DII" in classe_str or "DI" in classe_str or classe_cod in {"A", "B", "DI", "DII"}:
                return "DIII-1"
            return "TITULAR"

        if "DIV" in classe_str or classe_cod == "DIV":
            base = "DIV"
        elif "DIII" in classe_str or classe_cod == "DIII":
            base = "DIII"
        elif "DII" in classe_str or classe_cod == "DII":
            base = "DII"
        elif "DI" in classe_str or classe_cod == "DI":
            base = "DI"
        else:
            base = classe_cod
        return f"{base}-{padrao_num + 1}"

    # PCCTAE: padrões 1..19 (Lei 15.141/2025)
    if padrao_num >= PCCTAE_PADRAO_MAX:
        return f"{classe_cod}-{PCCTAE_PADRAO_MAX}"
    return f"{classe_cod}-{padrao_num + 1}"


def posicionamento_atual(classe, padrao, cargo=""):
    c_atual = limpar_classe(classe)
    if c_atual in {"T", "TITULAR"} or "TITULAR" in str(classe).upper():
        return "TITULAR"
    is_ebtt = "PROFESSOR" in str(cargo).upper()
    p_atual = extrair_padrao(padrao, maximo=4 if is_ebtt else PCCTAE_PADRAO_MAX)
    return f"{c_atual}-{p_atual}"


def classificar_progressao(pos_atual, pos_nova, db, prox_data, titulacao, cargo):
    """
    Retorna (pos_nova_ajustada, efeitos_financeiros, observacao)
    efeitos_financeiros: 'Sim' | 'Não'
    """
    is_ebtt = "PROFESSOR" in str(cargo).upper()

    # 1) Já no topo (Titular ou PCCTAE-19)
    if str(pos_atual).upper() == "TITULAR" or pos_atual == pos_nova:
        label = pos_atual
        return (
            f"JÁ NO TOPO ({label})",
            "Não",
            "Somente Avaliação de Desempenho. Sem efeitos financeiros — final de carreira",
        )

    # 2) Promoção a Titular (ex.: C-4 / DIV-4 → TITULAR)
    if is_ebtt and str(pos_nova).upper() == "TITULAR":
        tempo_ok = False
        if pd.notna(db):
            base = db.date() if hasattr(db, "date") else db
            tempo_ok = relativedelta(prox_data, base).years >= 2

        doutorado_ok = tem_doutorado(titulacao)
        pendencias = []
        if not tempo_ok:
            pendencias.append("tempo mínimo de 2 anos no nível atual")
        if not doutorado_ok:
            pendencias.append("diploma de doutorado")

        if pendencias:
            return (
                f"{pos_nova} (PENDENTE)",
                "Não",
                "Somente Avaliação de Desempenho. Falta: " + "; ".join(pendencias),
            )
        return (
            pos_nova,
            "Não",
            "Somente Avaliação de Desempenho. Promoção a Titular — sem efeitos financeiros (requisitos atendidos)",
        )

    # 3) Progressão ordinária
    return (pos_nova, "Sim", "Progressão com efeitos financeiros")


def formatar_funcao_display(funcao_str):
    if pd.isna(funcao_str):
        return ""
    match = re.match(r"([A-Z]+)(\d+)", str(funcao_str).split(" - ")[0].strip().upper())
    if match:
        return f"{match.group(1)}-{int(match.group(2))}"
    return str(funcao_str).split(" - ")[0].strip()


def construir_indice_setores(df_completo):
    indice = {}
    if "SETOR_NORM" not in df_completo.columns:
        return indice
    for setor, grupo in df_completo.groupby("SETOR_NORM", dropna=False):
        if not setor or setor in {"NAN", "NONE"}:
            continue
        indice[setor] = grupo.copy()
    return indice


def identificar_chefia_e_pares(setor, indice_setores, servidor_atual=None):
    if pd.isna(setor) or str(setor).strip() == "":
        return "N/A", "Nenhum"

    setor_str = str(setor).strip().upper()
    df_setor = indice_setores.get(setor_str)
    if df_setor is None or df_setor.empty:
        return "N/A", "Nenhum"

    funcao = df_setor.get("FUNCAO DISPLAY", pd.Series("", index=df_setor.index))
    valid_funcao = funcao.astype(str).str.upper().str.startswith(("FG", "CD"), na=False)
    situacao = df_setor.get("SITUACAO", pd.Series("", index=df_setor.index)).astype(str).str.strip().str.upper()

    chefes_df = df_setor[valid_funcao & situacao.isin(SITUACOES_CHEFIA)]
    substitutos_df = df_setor[valid_funcao & (situacao == SITUACAO_SUBSTITUTO)]

    chefes = sorted({
        f"{r['SERVIDOR']} ({formatar_funcao_display(r.get('FUNCAO DISPLAY'))})"
        for _, r in chefes_df.iterrows()
    })
    subst = sorted({
        f"{r['SERVIDOR']} ({formatar_funcao_display(r.get('FUNCAO DISPLAY'))})"
        for _, r in substitutos_df.iterrows()
    })

    partes = []
    if chefes:
        partes.append(", ".join(chefes))
    if subst:
        partes.append(f"Substitutos: {', '.join(subst)}")
    chefia_str = "; ".join(partes) if partes else "N/A"

    pares_df = df_setor[(~valid_funcao) & (~situacao.isin(SITUACOES_EXCLUIDAS_PARES))]
    if servidor_atual is not None:
        pares_df = pares_df[pares_df["SERVIDOR"].astype(str).str.upper() != str(servidor_atual).upper()]
    pares_list = sorted(pares_df["SERVIDOR"].dropna().astype(str).unique().tolist())
    return chefia_str, ", ".join(pares_list) if pares_list else "Nenhum"


def construir_indice_afastamentos(afastamentos_df):
    indice = defaultdict(list)
    if afastamentos_df is None or afastamentos_df.empty or "MATRICULA_EXTRAIDA" not in afastamentos_df.columns:
        return indice

    col_tipo = next((c for c in ["COD AFASTAMENTO", "OCORRÊNCIA", "OCORRENCIA"] if c in afastamentos_df.columns), None)
    col_ini = next((c for c in ["DIA INICIO AFASTAMENTO", "DATA INÍCIO", "DATA INICIO"] if c in afastamentos_df.columns), None)
    col_fim = next((c for c in ["DIA FIM AFASTAMENTO", "DATA FIM"] if c in afastamentos_df.columns), None)

    for _, row in afastamentos_df.iterrows():
        mat = str(row.get("MATRICULA_EXTRAIDA", "")).strip()
        if not mat:
            continue
        indice[mat].append({
            "tipo": str(row.get(col_tipo) if col_tipo else "Ocorrência").strip() or "Ocorrência",
            "inicio": row.get(col_ini),
            "fim": row.get(col_fim),
        })
    return indice


def _para_data(valor):
    if pd.isna(valor):
        return None
    if hasattr(valor, "date"):
        try:
            return valor.date()
        except Exception:
            pass
    ts = pd.to_datetime(valor, errors="coerce", dayfirst=True)
    if pd.isna(ts):
        return None
    return ts.date()


def get_afastamentos_info(matricula, inicio_intersticio, fim_intersticio, indice_afast):
    registros = indice_afast.get(str(matricula).strip(), [])
    if not registros:
        return "Nenhum", "Nenhum"

    validos, outros = [], []
    for item in registros:
        d_ini = _para_data(item["inicio"])
        d_fim = _para_data(item["fim"])
        if d_ini is None or d_fim is None:
            continue
        delta = (min(fim_intersticio, d_fim) - max(inicio_intersticio, d_ini)).days + 1
        per_str = f"{d_ini.strftime('%d/%m/%Y')} a {d_fim.strftime('%d/%m/%Y')}"
        texto = f"{item['tipo']} ({per_str}"
        if delta > 0:
            validos.append(f"{texto} | {delta} dias no interstício)")
        else:
            outros.append(f"{texto})")

    af_periodo = "<br>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;• ".join(validos) if validos else "Nenhum"
    af_outros = "<br>&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;• ".join(outros) if outros else "Nenhum"
    return af_periodo, af_outros


def senha_cpf(cpf):
    if pd.isna(cpf):
        return "000"
    apenas = str(cpf).strip().replace(".", "").replace("-", "")
    return (apenas[:3] or "000")


