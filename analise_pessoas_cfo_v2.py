def normalizar_servidores(df):
    out = df.copy()
    out.columns = [str(c).strip() for c in out.columns]

    if "SERVIDOR" in out.columns:
        out["SERVIDOR"] = out["SERVIDOR"].astype(str).str.strip()

    date_cols = [
        "DATA POSSE NO CARGO",
        "DATA ULTIMA PROGRESSAO",
        "DATA DE NASCIMENTO",
        "CARGO EMPREGO DATA SAIDA",
    ]
    for col in date_cols:
        if col in out.columns and not is_datetime64_any_dtype(out[col]):
            out[col] = pd.to_datetime(out[col], errors="coerce", dayfirst=True)

    for col in ["SEXO", "SITUACAO", "TITULACAO", "APOSENTADORIA"]:
        if col in out.columns:
            out[col] = out[col].astype(str).str.strip()

    if "MATRICULA" in out.columns:
        out["MATRICULA_NORMALIZADA"] = (
            out["MATRICULA"].astype(str).str.strip().str.replace(r"\.0$", "", regex=True)
        )

    if "SETOR EXERCICIO" in out.columns:
        out["SETOR_NORM"] = out["SETOR EXERCICIO"].astype(str).str.strip().str.upper()
    else:
        out["SETOR_NORM"] = ""

    return out


