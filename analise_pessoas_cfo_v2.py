def load_csv_from_drive_by_name(file_name, creds, nome="planilha", folder_id=None):
    """
    Loads a CSV file (or Google Sheet exported as CSV) from Google Drive by its name into a pandas DataFrame.
    """
    try:
        service = build('drive', 'v3', credentials=creds)

        query = f"name = '{file_name}' and trashed = false"
        if folder_id:
            query = f"'{folder_id}' in parents and {query}"

        results = service.files().list(q=query, fields="files(id, name, mimeType)").execute()
        items = results.get('files', [])

        if not items:
            print(f"[ERRO] {nome}: Nenhum arquivo '{file_name}' encontrado no Google Drive.")
            return pd.DataFrame()
        elif len(items) > 1:
            print(f"[AVISO] {nome}: Múltiplos arquivos '{file_name}' encontrados. Usando o primeiro: '{items[0]['name']}' (ID: {items[0]['id']}).")
            file_id = items[0]['id']
            file_mime_type = items[0]['mimeType']
        else:
            file_id = items[0]['id']
            file_mime_type = items[0]['mimeType']
            print(f"[OK] {nome}: Arquivo '{file_name}' (ID: {file_id}, MIME Type: {file_mime_type}) encontrado.")

        # Download the file content, handling Google Sheets specifically
        if file_mime_type == 'application/vnd.google-apps.spreadsheet':
            # Export Google Sheet as CSV
            request = service.files().export_media(
                fileId=file_id, mimeType='text/csv')
        elif file_mime_type == 'text/csv':
            # Download regular CSV file
            request = service.files().get_media(fileId=file_id)
        else:
            print(f"[ERRO] {nome}: Tipo de arquivo '{file_mime_type}' não suportado. Esperava 'text/csv' ou 'application/vnd.google-apps.spreadsheet'.")
            return pd.DataFrame()

        downloaded_content = io.BytesIO(request.execute())

        df = pd.read_csv(downloaded_content)
        print(f"[OK] {nome}: {len(df)} linhas, {len(df.columns)} colunas")
        return df

    except Exception as exc:
        print(f"[ERRO] Falha ao carregar {nome} do Drive: {exc}")
        return pd.DataFrame()


